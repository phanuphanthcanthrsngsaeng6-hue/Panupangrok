var MAX_BINDING_FILE_BYTES = 16 * 1024;

class InvalidRuntimeBindingRecordError extends Error {
}
async function readActiveRuntimeProjectTarget(sessionUid, expectedProjectDir, addonDataDirectory, requireHostLocalBinding = false, workspaceRoot) {
  const active = await readActiveRuntimeProjectRecord(sessionUid, addonDataDirectory, requireHostLocalBinding);
  if (!active)
    return;
  if (requireHostLocalBinding && !isActiveLocalRuntimeProjectBinding(active))
    throw new Error("local runtime project binding is unavailable");
  if (isActiveLocalRuntimeProjectBinding(active)) {
    const invocationDirectory = expectedProjectDir && await fs3.realpath(expectedProjectDir);
    const selectedDirectory = active.workingDirectory && invocationDirectory === active.workingDirectory ? active.projectDir : expectedProjectDir ?? active.projectDir;
    await assertLocalProjectDirectoryAccess({ sessionId: sessionUid, workingDirectory: active.workingDirectory ?? expectedProjectDir ?? active.projectDir, workspaceRoot, projectDirectory: await localProjectDirectory(selectedDirectory) });
    const target = await findLocalProjectManifest(selectedDirectory, workspaceRoot, selectedDirectory === active.projectDir);
    if (!target || target.projectId !== active.resourceId) {
      throw new Error("active local website declaration is missing or changed; reattach the intended website");
    }
    const previous = await localProjectDirectory(active.projectDir).catch(() => {
      return;
    });
    if (previous && target.projectDir !== previous) {
      throw new Error("active local website does not match this invocation");
    }
    return { resourceId: active.resourceId, projectDir: target.projectDir };
  }
  const binding = await readRuntimeProjectBinding(active.resourceId, runtimeProjectBindingDirectory());
  return {
    resourceId: active.resourceId,
    projectDir: binding.projectDir,
    ...binding.legacyAdoptionPath ? { legacyAdoptionPath: binding.legacyAdoptionPath } : {}
  };
}
async function readWorkspaceProjectTargetForDirectory(projectDir) {
  const actual = await fs3.realpath(projectDir);
  const directories = [runtimeProjectBindingDirectory()];
  let match;
  let invalidRecord;
  const seen = new Set;
  for (const directory of directories) {
    let entries;
    try {
      entries = await fs3.opendir(directory);
    } catch (error) {
      if (error.code === "ENOENT")
        continue;
      throw error;
    }
    let count = 0;
    for await (const entry of entries) {
      if (++count > 2048)
        throw new Error("runtime binding directory exceeds lookup limit");
      const resourceId = entry.name.endsWith(".json") ? entry.name.slice(0, -5) : "";
      if (!WEBDEV_CONFIG_PLANE_RESOURCE_ID_PATTERN.test(resourceId) || seen.has(resourceId))
        continue;
      seen.add(resourceId);
      let binding;
      try {
        binding = await readRuntimeProjectBinding(resourceId, directory);
      } catch (error) {
        if (error instanceof InvalidRuntimeBindingRecordError) {
          invalidRecord ??= error;
          continue;
        }
        if (error.code === "ENOENT")
          continue;
        throw error;
      }
      const projectDir2 = binding.projectDir;
      let resolved;
      try {
        resolved = await fs3.realpath(projectDir2);
      } catch (error) {
        if (error.code === "ENOENT")
          continue;
        throw error;
      }
      if (resolved !== actual)
        continue;
      if (match)
        throw new Error("runtime workspace binding is ambiguous");
      match = { resourceId, projectDir: projectDir2 };
    }
  }
  if (!match && invalidRecord)
    throw invalidRecord;
  return match;
}
function runtimeProjectBindingDirectory(options) {
  const explicit = options?.ignoreEnvironment ? undefined : process.env.WEBDEV_RUNTIME_BINDING_DIR?.trim();
  if (explicit)
    return explicit;
  const addonDataDirectory = options?.addonDataDirectory?.trim() ?? process.env.MANUS_ADDON_DATA_DIRECTORY?.trim();
  if (addonDataDirectory) {
    if (!path3.isAbsolute(addonDataDirectory) || path3.normalize(addonDataDirectory) !== addonDataDirectory || addonDataDirectory === path3.parse(addonDataDirectory).root || /[\u0000-\u001f\u007f]/.test(addonDataDirectory)) {
      throw new Error("Addon data directory is invalid");
    }
    return path3.join(addonDataDirectory, "runtime-bindings");
  }
  if (options?.requireHostDataDirectory || process.env.WEBDEV_INIT_RUNNER?.trim() === "local") {
    throw new Error("Addon data directory is unavailable");
  }
  return path3.join(os.homedir(), ".manus-addons", "data", "manus-webdev", "runtime-bindings");
}
function activeRuntimeProjectBindingPath(bindingDir, sessionUid) {
  const sessionKey = runtimeSessionKey(sessionUid);
  return path3.join(bindingDir, `active-${sessionKey}.json`);
}
function runtimeSessionKey(sessionUid) {
  if (!isRuntimeSessionUid(sessionUid)) {
    throw new Error("runtime session identity is invalid");
  }
  return crypto.createHash("sha256").update(sessionUid).digest("hex");
}
function isRuntimeSessionUid(sessionUid) {
  return Boolean(sessionUid.trim()) && sessionUid.length <= 1024 && !/[\u0000-\u001f\u007f]/.test(sessionUid);
}
async function readRuntimeProjectBinding(resourceId, bindingDir) {
  if (!WEBDEV_CONFIG_PLANE_RESOURCE_ID_PATTERN.test(resourceId)) {
    throw new Error("runtime project binding Resource is invalid");
  }
  const value = await readSafeBindingJSON(path3.join(bindingDir, `${resourceId}.json`));
  if (!isWorkspaceRuntimeProjectBinding(value) || value.resourceId !== resourceId) {
    throw new InvalidRuntimeBindingRecordError("runtime project binding identity is invalid");
  }
  return value;
}
async function readSafeBindingJSON(target) {
  const info = await fs3.lstat(target);
  if (!info.isFile() || process.platform !== "win32" && (info.mode & 18) !== 0 || info.size <= 0 || info.size > MAX_BINDING_FILE_BYTES) {
    throw new InvalidRuntimeBindingRecordError("runtime project binding file is unsafe");
  }
  const raw = await fs3.readFile(target, "utf8");
  try {
    return JSON.parse(raw);
  } catch {
    throw new InvalidRuntimeBindingRecordError("runtime project binding file is malformed");
  }
}
function isWorkspaceRuntimeProjectBinding(value) {
  if (!isPlainRecord(value)) {
    return false;
  }
  if (Object.keys(value).sort().join(",") !== (value.legacyAdoptionPath === undefined ? "attemptId,projectDir,projectName,resourceId,schema" : "attemptId,legacyAdoptionPath,projectDir,projectName,resourceId,schema") || value.legacyAdoptionPath !== undefined && value.legacyAdoptionPath !== value.projectDir) {
    return false;
  }
  return value.schema === WORKSPACE_RUNTIME_PROJECT_BINDING_SCHEMA && hasValidWorkspaceBindingFields(value);
}
function hasValidWorkspaceBindingFields(value) {
  return typeof value.resourceId === "string" && WEBDEV_CONFIG_PLANE_RESOURCE_ID_PATTERN.test(value.resourceId) && typeof value.projectName === "string" && (PROJECT_NAME_PATTERN.test(value.projectName) || value.legacyAdoptionPath === value.projectDir && typeof value.legacyAdoptionPath === "string" && value.projectName.length <= 255 && value.projectName.trim().length > 0 && !/[\/\\\r\n\0]/.test(value.projectName) && ![".", ".."].includes(value.projectName)) && typeof value.projectDir === "string" && path3.isAbsolute(value.projectDir) && typeof value.attemptId === "string" && ATTEMPT_ID_PATTERN.test(value.attemptId);
}
function isActiveRuntimeProjectBinding(value) {
  return isPlainRecord(value) && Object.keys(value).sort().join(",") === "resourceId,schema" && value.schema === ACTIVE_RUNTIME_PROJECT_BINDING_SCHEMA && typeof value.resourceId === "string" && WEBDEV_CONFIG_PLANE_RESOURCE_ID_PATTERN.test(value.resourceId);
}
function isActiveLocalRuntimeProjectBinding(value) {
  if (!isPlainRecord(value))
    return false;
  const keys = Object.keys(value).sort().join(",");
  const validVersion = value.schema === ACTIVE_LOCAL_RUNTIME_PROJECT_BINDING_SCHEMA ? keys === "projectDir,resourceId,schema,sessionKey" : value.schema === SELECTED_LOCAL_RUNTIME_PROJECT_BINDING_SCHEMA && keys === "projectDir,resourceId,schema,sessionKey,workingDirectory" && typeof value.workingDirectory === "string" && path3.isAbsolute(value.workingDirectory);
  return validVersion && typeof value.sessionKey === "string" && /^[a-f0-9]{64}$/.test(value.sessionKey) && typeof value.resourceId === "string" && WEBDEV_CONFIG_PLANE_RESOURCE_ID_PATTERN.test(value.resourceId) && typeof value.projectDir === "string" && path3.isAbsolute(value.projectDir);
}
function decodeActiveLocalRuntimeProjectBinding(value) {
  if (isActiveLocalRuntimeProjectBinding(value))
    return value;
  if (!isPlainRecord(value) || value.schema !== "manus.webdev.active_local_runtime_project_binding/v2" || Object.keys(value).sort().join(",") !== "gitCommonDir,gitCommonDirIdentity,projectDir,projectRelativePath,resourceId,schema,sessionKey" || typeof value.gitCommonDir !== "string" || !path3.isAbsolute(value.gitCommonDir) || typeof value.gitCommonDirIdentity !== "string" || !/^[a-f0-9]{64}$/.test(value.gitCommonDirIdentity) || typeof value.projectRelativePath !== "string" || path3.isAbsolute(value.projectRelativePath) || value.projectRelativePath.split(/[\\/]/).includes("..") || /[\u0000-\u001f\u007f]/.test(value.projectRelativePath))
    return;
  const normalized = {
    schema: ACTIVE_LOCAL_RUNTIME_PROJECT_BINDING_SCHEMA,
    sessionKey: value.sessionKey,
    resourceId: value.resourceId,
    projectDir: value.projectDir
  };
  return isActiveLocalRuntimeProjectBinding(normalized) ? normalized : undefined;
}
async function readActiveRuntimeProjectRecord(sessionUid, addonDataDirectory, requireHostLocalBinding = false) {
  if (!isRuntimeSessionUid(sessionUid))
    return;
  if (requireHostLocalBinding && !addonDataDirectory)
    throw new Error("Addon data directory is unavailable");
  const bindingDir = runtimeProjectBindingDirectory({
    addonDataDirectory,
    requireHostDataDirectory: addonDataDirectory !== undefined,
    ignoreEnvironment: requireHostLocalBinding
  });
  const target = activeRuntimeProjectBindingPath(bindingDir, sessionUid);
  let value;
  try {
    value = await readSafeBindingJSON(target);
  } catch (error) {
    if (error.code === "ENOENT")
      return;
    throw error;
  }
  const local = decodeActiveLocalRuntimeProjectBinding(value);
  if (local) {
    if (local.sessionKey !== runtimeSessionKey(sessionUid)) {
      throw new Error("active local runtime project session identity is invalid");
    }
    return local;
  }
  if (requireHostLocalBinding)
    throw new Error("local runtime project binding is unavailable");
  if (!isActiveRuntimeProjectBinding(value)) {
    throw new Error("active runtime project binding identity is invalid");
  }
  await readRuntimeProjectBinding(value.resourceId, bindingDir);
  return value;
}
function isPlainRecord(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

