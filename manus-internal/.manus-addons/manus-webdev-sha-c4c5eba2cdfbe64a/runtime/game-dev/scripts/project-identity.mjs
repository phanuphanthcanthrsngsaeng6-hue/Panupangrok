async function projectResourceId(root, { required = true } = {}) {
  const sessionUid = process.env.MANUS_SESSION_ID ?? process.env.MANUS_SANDBOX_SESSION ?? "";
  const dataDirectory = process.env.MANUS_ADDON_DATA_DIRECTORY?.trim() || undefined;
  const local = process.env.WEBDEV_INIT_RUNNER === "local";
  let target;
  let unmatchedInvalidBinding;
  try {
    if (!sessionUid && !local) {
      try {
        target = await readWorkspaceProjectTargetForDirectory(root);
      } catch (error) {
        if (!(error instanceof InvalidRuntimeBindingRecordError) || dataDirectory)
          throw error;
        unmatchedInvalidBinding = error;
      }
    } else {
      target = await readActiveRuntimeProjectTarget(sessionUid, root, dataDirectory, local);
    }
    if (target) {
      const actual = await realpath(root);
      const expected = await realpath(target.projectDir);
      if (actual !== expected)
        throw new Error("Workspace binding mismatch");
      return target.resourceId;
    }
    if (!sessionUid && !local && !dataDirectory) {
      const declaration = await readLocalProjectManifest(root);
      if (declaration)
        return declaration.projectId;
    }
    if (unmatchedInvalidBinding)
      throw unmatchedInvalidBinding;
  } catch {
    if (required)
      throw new Error("Game runtime project binding is invalid; attach the intended project again");
    return null;
  }
  if (required)
    throw new Error("Game runtime project binding is unavailable; attach the intended project first");
  return null;
}
async function previewResourceId(root) {
  const bound = await projectResourceId(root, { required: false });
  if (bound)
    return bound;
  try {
    return (await readLocalProjectManifest(root))?.projectId ?? null;
  } catch {
    return null;
  }
}
