import { existsSync, readFileSync, lstatSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { BACKEND_CONTRACT, readBackendContract } from './leaderboard-reference/server/backend-contract.mjs'
import { readWebExportConfiguration } from './scripts/web-export.mjs'

const reference = fileURLToPath(new URL('./auth-reference/', import.meta.url))
function authServerFiles(source) {
  return ['app.mjs', 'routers.mjs', 'webdev-adapter.mjs', 'index.mjs', 'package.json', '0000_initial_users.sql', 'Dockerfile']
    .map(name => [name, readFileSync(join(source, 'server', name))])
}
// This is an opt-in project addition, never a rewrite of frozen starter revisions.
export function installGameAuth(root, source = reference, engine = 'godot') {
  if (engine === 'threejs') return installThreejsAuth(root, source)
  if (engine !== 'godot') throw new Error('Unsupported game engine')
  root = resolve(root)
  const generatedShell = readWebExportConfiguration(root)?.shell
  if (generatedShell) {
    throw new Error(`Customized loader preserved: res://${generatedShell.output} is generated by ${generatedShell.builder}; ` +
      'adapt the generator source to wire ManusAuth.startGame before engine startup explicitly')
  }
  // The export preset selects the actual shell. Do not patch an unused loading.html,
  // or generated/custom shells whose startup is owned by another source file.
  const presets = join(root, 'export_presets.cfg')
  const presetStat = lstatSync(presets, { throwIfNoEntry: false })
  if (presetStat) {
    if (!presetStat.isFile()) throw new Error('Customized loader preserved: export_presets.cfg must be a regular file')
    const shells = [...readFileSync(presets, 'utf8').matchAll(/^\s*html\/custom_html_shell\s*=([^\r\n]*)/gm)].map(match => match[1].trim())
    if (!shells.length || shells.some(shell => shell !== '"res://web/loading.html"')) {
      const generated = shells.includes('"res://web/shell.html"') && existsSync(join(root, 'web/build-shell.mjs')) && existsSync(join(root, 'web/loader.js'))
      throw new Error(`Customized loader preserved: ${shells.join(', ') || 'default shell (no html/custom_html_shell declared)'} in export_presets.cfg; ` +
        (generated ? 'adapt web/loader.js and regenerate web/shell.html with web/build-shell.mjs; ' : 'adapt the authored loader (or its generator); ') +
        'wire ManusAuth.startGame before engine startup explicitly')
    }
  }
  for (const relative of ['project.godot', 'web', 'web/loading.html']) {
    const target = join(root, relative)
    if (!existsSync(target) || lstatSync(target).isSymbolicLink()) throw new Error(`Regular Game source required: ${relative}`)
  }
  if (existsSync(join(root, 'server'))) throw new Error('Existing backend preserved; integrate the Webdev adapter into that backend instead')
  if (lstatSync(join(root, BACKEND_CONTRACT), { throwIfNoEntry: false })) throw new Error('Existing backend contract preserved; integrate authentication explicitly')
  const bridge = join(root, 'scripts/manus_auth.gd')
  if (existsSync(bridge) || (existsSync(join(root, 'scripts')) && lstatSync(join(root, 'scripts')).isSymbolicLink())) throw new Error('Existing or symbolic scripts preserved')
  const loader = readFileSync(join(root, 'web/loading.html'), 'utf8')
  const call = 'await engine.startGame({ onProgress });'
  if (loader.split(call).length !== 2 || loader.split('</head>').length !== 2 || loader.includes('ManusAuth')) throw new Error('Customized loader preserved; wire ManusAuth.startGame before engine startup explicitly')
  const project = readFileSync(join(root, 'project.godot'), 'utf8')
  if (/^ManusAuth\s*=/m.test(project)) throw new Error('Existing ManusAuth autoload preserved')
  // Preflight all packaged inputs before writing project files.
  const contract = readBackendContract(source, { required: true }).value
  if (contract.schema !== 'manus.game.auth-backend-contract/v1') throw new Error('Packaged auth backend contract is invalid')
  const server = authServerFiles(source)
  const browser = readFileSync(join(source, 'web/manus-auth-inline.js'), 'utf8')
  const godot = readFileSync(join(source, 'godot/manus_auth.gd'))
  const html = loader.replace('</head>', `<script>\n${browser}\n</script>\n</head>`)
    .replace(call, 'await ManusAuth.startGame(() => engine.startGame({ onProgress }));')
  const autoload = 'ManusAuth="*res://scripts/manus_auth.gd"'
  const updated = project.includes('[autoload]') ? project.replace('[autoload]', `[autoload]\n${autoload}`) : `${project}\n[autoload]\n${autoload}\n`
  mkdirSync(join(root, 'server'))
  for (const [name, content] of server) writeFileSync(join(root, 'server', name), content, { flag: 'wx' })
  mkdirSync(dirname(bridge), { recursive: true })
  writeFileSync(bridge, godot, { flag: 'wx' })
  writeFileSync(join(root, 'web/loading.html'), html)
  writeFileSync(join(root, 'project.godot'), updated)
  return {
    installed: true, configurationApplied: false,
    configurationPatch: {
      features: { server: true, database: true },
      build: { command: 'true', outputDirectory: 'site' },
      deploy: { dockerfilePath: contract.deploy.dockerfilePath, healthPath: contract.deploy.healthPath },
      routes: contract.routes,
    },
    nextSteps: ['Merge configurationPatch through the existing config API, preserving unrelated settings.',
      'Implement gameplay and Checkout creation as Webdev protectedProcedure mutations in server/routers.mjs; call ManusAuth.query/mutate through the browser bridge.',
      'Install server dependencies and commit package-lock.json; apply the copied Webdev users migration to the isolated project database using the normal migration workflow.',
      'Save a checkpoint and verify its real online Preview; resident Game Preview remains offline.'],
  }
}
// Three.js uses Webdev's browser login, callback and protected tRPC procedures.
function installThreejsAuth(root, source) {
  root = resolve(root)
  for (const relative of ['package.json', 'index.html']) {
    const stat = lstatSync(join(root, relative), { throwIfNoEntry: false })
    if (!stat?.isFile()) throw new Error(`Regular Three.js source required: ${relative}`)
  }
  for (const relative of ['server', 'manus-auth.js', 'manus-auth.d.ts', BACKEND_CONTRACT]) {
    if (lstatSync(join(root, relative), { throwIfNoEntry: false })) throw new Error('Existing backend preserved; integrate the Webdev adapter into that backend instead')
  }
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  if (!pkg.dependencies?.three) throw new Error('A Three.js project is required')
  const htmlPath = join(root, 'index.html')
  const html = readFileSync(htmlPath, 'utf8')
  if (html.split('</head>').length !== 2 || html.includes('ManusAuth')) throw new Error('Customized loader preserved; integrate ManusAuth explicitly')
  const server = authServerFiles(source)
  const browser = readFileSync(join(source, 'web/manus-auth.js'))
  const declarations = readFileSync(join(source, 'web/manus-auth.d.ts'))
  const dependencies = JSON.parse(readFileSync(join(source, 'web/browser-dependencies.json'), 'utf8'))
  for (const [name, version] of Object.entries(dependencies)) {
    if ((pkg.dependencies?.[name] || pkg.devDependencies?.[name]) && (pkg.dependencies?.[name] || pkg.devDependencies?.[name]) !== version) {
      throw new Error(`Existing ${name} dependency preserved; integrate the Webdev client explicitly`)
    }
  }
  mkdirSync(join(root, 'server'))
  for (const [name, content] of server) writeFileSync(join(root, 'server', name), content, { flag: 'wx' })
  writeFileSync(join(root, 'manus-auth.js'), browser, { flag: 'wx' })
  writeFileSync(join(root, 'manus-auth.d.ts'), declarations, { flag: 'wx' })
  writeFileSync(join(root, 'package.json'), JSON.stringify({ ...pkg, dependencies: { ...pkg.dependencies, ...dependencies } }, null, 2) + '\n')
  writeFileSync(htmlPath, html.replace('</head>', '<script type="module" src="/manus-auth.js"></script>\n</head>'))
  return {
    installed: true, configurationApplied: false,
    configurationPatch: {
      features: { server: true, database: true },
      build: { command: 'pnpm build', outputDirectory: 'dist' },
      deploy: { dockerfilePath: 'server/Dockerfile', healthPath: '/api/health' },
      routes: [{ path: '/api/*', target: 'server' }, { path: '/*', target: 'static' }],
    },
    nextSteps: [
      'Merge configurationPatch through the existing config API, preserving unrelated settings.',
      'Install project and server dependencies and commit their lockfiles; apply server/0000_initial_users.sql through the normal project migration workflow.',
      'Import { ManusAuth } from ../manus-auth.js in src/main.ts, call prepare(), and wire login/logout. Add protectedProcedure mutations to server/routers.mjs and call ManusAuth.mutate for gameplay writes and Stripe Checkout creation.',
      'Run the API with the injected server environment and proxy /api from Vite during development; use the normal Web checkpoint and hybrid deployment flow.',
    ],
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try { console.log(JSON.stringify(installGameAuth(process.cwd(), reference, process.argv.includes('--threejs') ? 'threejs' : 'godot'), null, 2)) }
  catch (error) { console.error(error.message); process.exitCode = 1 }
}
